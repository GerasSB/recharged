#!/usr/bin/env python3
"""Refresh the issue reporters thanked on the launcher's About page.

    python3 tools/update_issue_reporters.py

Lists everyone who opened an issue (bug report or feature request) on the
GitHub repository, pull requests, bots and the maintainer left out, and writes
them to src/launcher/issue_reporters.h. Needs the GitHub CLI (gh), signed in.
Run it before a release and commit the header when it changed.
"""

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "src" / "launcher" / "issue_reporters.h"
REPOSITORY = "previouslevelgames/recharged"
MAINTAINERS = {"yannicksuter"}


def reporters():
    result = subprocess.run(
        ["gh", "api", "--paginate", f"repos/{REPOSITORY}/issues?state=all&per_page=100",
         "--jq", ".[] | select(.pull_request == null) | .user | {login, type}"],
        check=True, capture_output=True, text=True)
    logins = set()
    for line in result.stdout.splitlines():
        user = json.loads(line)
        if user["type"] == "User" and user["login"] not in MAINTAINERS:
            logins.add(user["login"])
    return sorted(logins, key=str.casefold)


def main():
    names = reporters()
    lines = [
        "#pragma once",
        "",
        "// Everyone who reported a problem or asked for a feature on GitHub, thanked",
        "// on the About page. Generated by tools/update_issue_reporters.py.",
        "namespace mscharged::launcher",
        "{",
        "inline constexpr const char* kIssueReporters[] = {",
        *(f'    "{name}",' for name in names),
        "};",
        "} // namespace mscharged::launcher",
        "",
    ]
    text = "\n".join(lines)
    if HEADER.exists() and HEADER.read_text() == text:
        print(f"{len(names)} reporters, unchanged.")
        return
    HEADER.write_text(text)
    print(f"{len(names)} reporters written to {HEADER.relative_to(ROOT)}.")


if __name__ == "__main__":
    main()
